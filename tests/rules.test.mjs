import {readFile} from 'node:fs/promises';
import {test, before,after} from 'node:test';
import {initializeTestEnvironment,assertSucceeds,assertFails} from '@firebase/rules-unit-testing';
import {ref,set,get} from 'firebase/database';
let env,owner,guest,third;const room='rooms/AABBCCDDEEFF';
before(async()=>{env=await initializeTestEnvironment({projectId:'demo-waraqa',database:{host:'127.0.0.1',port:9000,rules:await readFile(new URL('../database.rules.json',import.meta.url),'utf8')}});owner=env.authenticatedContext('owner').database();guest=env.authenticatedContext('guest').database();third=env.authenticatedContext('third').database();});
after(async()=>{await env?.cleanup();});
test('two seats, private reads, isolated edits and validated data',async()=>{
 await assertSucceeds(set(ref(owner,room),{owner:'owner',settings:{mode:'split',seed:0,round:'one'}}));
 await assertFails(get(ref(guest,room)));
 const results=await Promise.allSettled([set(ref(guest,room+'/guest'),'guest'),set(ref(third,room+'/guest'),'third')]);
 if(results.filter(r=>r.status==='fulfilled').length!==1)throw Error('Exactly one guest must win');
 const winner=(await get(ref(owner,room+'/guest'))).val(),guestDb=winner==='guest'?guest:third,outsider=winner==='guest'?third:guest;
 await assertSucceeds(get(ref(guestDb,room)));
 await assertFails(get(ref(outsider,room)));
 await assertFails(set(ref(outsider,room+'/guest'),'intruder'));
 await assertFails(set(ref(guestDb,room+'/owner'),winner));
 await assertFails(set(ref(guestDb,room+'/guest'),null));
 await assertFails(set(ref(owner,room),null));
 await assertFails(set(ref(guestDb,room+'/settings'),{mode:'free',seed:0,round:'two'}));
 const stroke={uid:'owner',round:'one',side:'left',tool:'brush',color:'#123456',size:12,opacity:.8,visible:true,points:'[[100,100,0.7]]'};
 await assertSucceeds(set(ref(owner,room+'/strokes/a'),stroke));
 await assertFails(set(ref(guestDb,room+'/strokes/a'),{...stroke,uid:winner,side:'right'}));
 await assertFails(set(ref(owner,room+'/strokes/b'),{...stroke,side:'right'}));
 await assertFails(set(ref(owner,room+'/strokes/b'),{...stroke,size:10000}));
 await assertFails(set(ref(owner,room+'/strokes/b'),{...stroke,extra:true}));
 await assertSucceeds(set(ref(guestDb,room+'/strokes/b'),{...stroke,uid:winner,side:'right'}));
 await assertSucceeds(set(ref(owner,room+'/strokes/a/visible'),false));
 await assertSucceeds(set(ref(owner,room+'/presence/owner/tab1'),true));
 await assertFails(set(ref(guestDb,room+'/presence/owner/tab2'),true));
 await assertSucceeds(set(ref(owner,room+'/presence/owner/tab1'),null));
 await assertFails(get(ref(env.unauthenticatedContext().database(),room)));
 await assertFails(set(ref(outsider,'rooms/112233445566/guest'),'third'));
});
